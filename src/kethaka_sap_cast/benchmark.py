# Run every model through the same backtest, save results, charts and a report:

#Command: uv run python -m kethaka_sap_cast.benchmark

import pandas as pd

from kethaka_sap_cast import config, models
from kethaka_sap_cast.charts import plot_error_by_days_ahead, plot_recent_forecasts
from kethaka_sap_cast.evaluation import backtest, score, score_by_days_ahead
from kethaka_sap_cast.features import add_model_columns

MODELS = {
    "Naive (last value)": models.naive,
    "Mean of last 7 days": models.mean_7d,
    "ARIMA (AIC-selected)": models.arima,
    "Prophet": models.prophet,
    "Prophet + 10-day rain": models.prophet_rain,
}
# Models drawn on the forecasts-vs-actual chart (more than two gets cluttered)
CHART_MODELS = ["Naive (last value)", "Prophet + 10-day rain"]

EXPERIMENTS = config.ROOT / "experiments"
FIGURES = config.REPORTS / "figures"

NOTES = """## How to read this
- Rolling-origin backtest: train on all days before each cut-off, forecast the next 7 days,
  move forward 7 days (40 folds, Apr-Dec 2025). Jan-Mar is training data only.
- Days when a tapper was present but did not tap are forecast but not scored.
- MAPE = average % error. RMSE = typical error in litres, penalising large misses.
- Weather-based models use observed rainfall for future days (ex-post evaluation),
  so their results are an upper bound; in use, rain comes from a weather forecast.
"""


def run() -> pd.DataFrame:
    data = add_model_columns(pd.read_csv(config.PROCESSED / "dataset.csv", parse_dates=["date"]))

    all_results, summary, by_horizon = {}, [], {}
    for name, model in MODELS.items():
        print(f"Backtesting: {name}")
        results = backtest(data, model, target=models.TARGET)
        all_results[name] = results
        summary.append({"model": name, **score(results)})
        by_horizon[name] = score_by_days_ahead(results)

    summary = pd.DataFrame(summary).sort_values("MAPE_%")
    by_horizon = pd.DataFrame(by_horizon)
    by_horizon.index.name = "days_ahead"

    EXPERIMENTS.mkdir(exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    summary.to_csv(EXPERIMENTS / "benchmark_summary.csv", index=False)
    by_horizon.to_csv(EXPERIMENTS / "benchmark_by_days_ahead.csv")

    plot_error_by_days_ahead(by_horizon, FIGURES / "05_error_by_days_ahead.png")
    plot_recent_forecasts(data, all_results, CHART_MODELS, FIGURES / "06_forecasts_vs_actual.png")

    report = (
        "# Benchmark results: 7-day sap forecast\n\n"
        "Generated by `uv run python -m kethaka_sap_cast.benchmark`.\n\n"
        "## Overall (scored days only)\n\n" + summary.to_markdown(index=False) + "\n\n"
        "## MAPE % by days ahead\n\n" + by_horizon.round(2).to_markdown() + "\n\n"
        "![Error by days ahead](figures/05_error_by_days_ahead.png)\n\n"
        "![Forecasts vs actual](figures/06_forecasts_vs_actual.png)\n\n" + NOTES
    )
    (config.REPORTS / "benchmark.md").write_text(report, encoding="utf-8")

    print("\n" + summary.to_markdown(index=False))
    return summary


if __name__ == "__main__":
    run()